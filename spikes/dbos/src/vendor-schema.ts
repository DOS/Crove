// Vendors the DBOS system schema as committed SQL, the way plan section 4.9 vendors pg-boss (`pnpm db:vendor:pgboss`).
//
//   node src/vendor-schema.ts [--from N] [--sdk-dir DIR] [--out FILE]
//
// Uses the SDK's own generator (the same code as `npx dbos schema --print-migrations`), then makes the script fit
// Crove's runner, which applies each file in one transaction:
//   - CREATE/DROP INDEX CONCURRENTLY becomes the plain statement (a fresh or small table; on a big table this runs in
//     the promote window, as for pg-boss);
//   - the whole script is guarded by the recorded DBOS schema version, so it is a no-op when already applied and
//     fails loudly when the database is at an unexpected version.
import { createRequire } from 'node:module';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SCHEMA } from './env.ts';

const here = dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const opt = (name: string) => {
  const i = args.indexOf(name);
  return i === -1 ? undefined : args[i + 1];
};
const from = Number(opt('--from') ?? '1');
const sdkDir = resolve(opt('--sdk-dir') ?? join(here, '..', 'node_modules', '@dbos-inc', 'dbos-sdk'));

const require = createRequire(import.meta.url);
const sdkVersion: string = require(join(sdkDir, 'package.json')).version;
// Not exported through the package's "exports" map, so it is loaded by path: the CLI's own print mode.
const schemaCli = require(join(sdkDir, 'dist', 'src', 'cli', 'schema.js'));
const migrations = require(join(sdkDir, 'dist', 'src', 'sysdb_migrations', 'internal', 'migrations.js'));
const target: number = migrations.allMigrations(SCHEMA).length;

const raw: string = schemaCli.generateMigrationSQL(SCHEMA, from);
const body = raw
  .split('\n')
  .filter((line) => !/^-- (This script|Contains CREATE\/DROP INDEX CONCURRENTLY)/.test(line))
  .join('\n')
  .replace(/\b(CREATE(?: UNIQUE)? INDEX|DROP INDEX)\s+CONCURRENTLY\b/g, '$1');

const expectedBefore = from - 1;
const guard = `-- Guard: apply only on a database at DBOS schema version ${expectedBefore} (0 = no schema yet).
DO $guard$
DECLARE v bigint := 0;
BEGIN
  IF to_regclass('"${SCHEMA}"."dbos_migrations"') IS NOT NULL THEN
    SELECT coalesce(max(version), 0) INTO v FROM "${SCHEMA}"."dbos_migrations";
  END IF;
  IF v <> ${expectedBefore} THEN
    RAISE EXCEPTION 'DBOS system schema is at version %, this file expects % (vendored from @dbos-inc/dbos-sdk ${sdkVersion})', v, ${expectedBefore};
  END IF;
END
$guard$;
`;

const sql = `-- Vendored DBOS Transact system schema: @dbos-inc/dbos-sdk ${sdkVersion}, migrations ${from}..${target}, schema "${SCHEMA}".
-- Generated by spikes/dbos/src/vendor-schema.ts from the SDK's own generator; do not edit by hand.
-- CONCURRENTLY removed so the file applies inside one transaction.
${guard}
${body.trim()}
`;

const out = resolve(opt('--out') ?? join(here, '..', 'sql', `dbos-${sdkVersion}-from-${from}.sql`));
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, sql);
console.log(JSON.stringify({ sdkVersion, from, target, out, bytes: sql.length }));
